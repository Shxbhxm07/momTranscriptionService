def _load_glossary():
    """Load the terminology glossary (termbase). Config-driven: edit glossary.json, no code change.
    Returns (dnt_list, terms_dict). Degrades to empty on any error so translation still works."""
    path = os.path.join(os.path.dirname(__file__), "glossary.json")
    try:
        with open(path, encoding="utf-8") as f:
            g = json.load(f)
        dnt = [t for t in g.get("dnt", []) if isinstance(t, str) and t.strip()]
        terms = {k: v for k, v in g.get("terms", {}).items()
                 if isinstance(k, str) and isinstance(v, dict)}
        return dnt, terms
    except Exception as e:  # noqa: BLE001
        logger.warning(f"[i18n] glossary.json not loaded ({e}); using empty glossary")
        return [], {}


