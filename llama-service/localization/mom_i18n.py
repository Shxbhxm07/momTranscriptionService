"""Config-driven MoM localization + rendering.

SINGLE SOURCE OF TRUTH for the Minutes-of-Meeting layout across every language. The LLM produces
ONLY structured content (see `CONTENT_SCHEMA` / `parse_content`); this module owns section order,
headings, field labels, separators, footer, speaker-label localization, and metadata placement.

Adding a new language = add ONE entry to MOM_LABELS. No business logic changes.

Forward-compatibility: the content is a set of structured objects (`header`, `attendees`,
`speaker_notes`, `action_items`). New sub-fields can be added to any object and the renderer keeps
working — `parse_content` ignores unknown keys and supplies defaults for missing ones.

Localization rules enforced here:
  * Fixed document strings (headings/labels/footer) come from MOM_LABELS — never the LLM.
  * Identifiers/proper nouns are never touched (they only live inside content values).
  * Generic speaker placeholders ([Speaker_1], Speaker A, ...) → localized "Speaker N".
  * Date/Time: LLM value used only if explicitly extracted (D2), else the deterministic backend
    metadata (ISO-8601 + 24h). The renderer never asks the LLM to format a date.
"""

