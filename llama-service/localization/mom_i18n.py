def _merged(name):
    """A language's labels layered over English.

    Non-English sets are allowed to be incomplete, and were: none of the five carried a
    `key_figures` label, so rendering a MoM with figures in Hindi raised KeyError inside the
    renderer. Layering over English means a missing label degrades to the English word — the
    section still renders — instead of taking the whole document down.
    """
    if name == "English":
        return MOM_LABELS["English"]
    return {**MOM_LABELS["English"], **MOM_LABELS[name]}


def labels_for(lang):
    """Resolve a language name (tolerant of aliases like 'chinese', 'zh') to its label set.
    Falls back to English so an unconfigured language degrades gracefully rather than breaking."""
    if not lang:
        return MOM_LABELS["English"]
    if lang in MOM_LABELS:
        return _merged(lang)
    low = lang.strip().lower()
    for name in MOM_LABELS:
        if name.lower() == low:
            return _merged(name)
    alias = {"chinese": "Chinese (Simplified)", "zh": "Chinese (Simplified)", "mandarin": "Chinese (Simplified)",
             "hindi": "Hindi", "hi": "Hindi", "russian": "Russian", "ru": "Russian",
             "hebrew": "Hebrew", "he": "Hebrew", "arabic": "Arabic", "ar": "Arabic",
             "english": "English", "en": "English"}
    for key, name in alias.items():
        if key in low:
            return _merged(name)
    return MOM_LABELS["English"]


# Generic speaker placeholder: [Speaker_1], Speaker A, speaker 3, [speaker_02] ...  A real name won't match.
_SPEAKER_RE = re.compile(r'^\[?\s*speaker[\s_]*([0-9]+|[A-Za-z])\s*\]?$', re.IGNORECASE)


def localize_speaker(value, L):
    """Generic speaker placeholder → localized 'Speaker N'. A real name passes through unchanged."""
    if not value:
        return value
    v = str(value).strip()
    m = _SPEAKER_RE.match(v)
    if not m:
        return v                      # real name / anything non-generic → keep verbatim
    tok = m.group(1)
    n = tok if tok.isdigit() else str(ord(tok.upper()) - 64)   # A->1, B->2, ...
    return f"{L['speaker']} {n}"


# ─────────────────────────────────────────────────────────────────────────────
# Parsing, validation, deterministic repair
# ─────────────────────────────────────────────────────────────────────────────
_CORE_KEYS = {"header", "topic", "agenda", "attendees", "summary",
              "speaker_notes", "decisions", "action_items", "purpose"}


def _extract_json(raw):
    """Pull a JSON object out of a model response, tolerating ```json fences and surrounding prose."""
    if isinstance(raw, dict):
        return raw
    s = (raw or "").strip()
    if "```" in s:
        parts = s.split("```")
        if len(parts) >= 2:
            s = parts[1]
            if s.lstrip().lower().startswith("json"):
                s = s.lstrip()[4:]
    a, b = s.find("{"), s.rfind("}")
    if a != -1 and b != -1 and b > a:
        s = s[a:b + 1]
    try:
        return json.loads(s)
    except Exception:
        return {}


def _repair_json(raw):
    """Deterministic (no-LLM) repair of common malformed-JSON issues: markdown fences, leading prose,
    trailing commas, and unclosed braces/brackets (truncated output). Returns a parsed dict or {}."""
    s = str(raw or "").strip()
    if "```" in s:
        parts = s.split("```")
        if len(parts) >= 2:
            s = parts[1]
            if s.lstrip().lower().startswith("json"):
                s = s.lstrip()[4:]
    a = s.find("{")
    if a == -1:
        return {}
    s = s[a:]
    s = re.sub(r',\s*([}\]])', r'\1', s)                 # trailing commas
    s = s + ("]" * max(0, s.count("[") - s.count("]")))  # close arrays
    s = s + ("}" * max(0, s.count("{") - s.count("}")))  # close objects
    try:
        return json.loads(s)
    except Exception:
        return {}


def is_valid_raw(data):
    """A response is valid if it is a JSON object carrying at least one recognized content key."""
    return isinstance(data, dict) and bool(_CORE_KEYS & set(data.keys()))


def parse_and_validate(raw):
    """Parse an LLM JSON response, with ONE deterministic repair retry before giving up.
    Returns (content_dict, ok). The renderer should only be called when ok is True."""
    data = _extract_json(raw)
    if not is_valid_raw(data):
        data = _repair_json(raw)          # single deterministic repair retry
    ok = is_valid_raw(data)
    return parse_content(data if ok else {}), ok


def _s(x):
    return str(x).strip() if x is not None else ""


def _list(x):
    return x if isinstance(x, list) else []


def _bullets(x):
    """List of strings, tolerant of [{"text": ...}] / [{"point": ...}] for forward-compat."""
    out = []
    for i in _list(x):
        if isinstance(i, dict):
            out.append(_s(i.get("text") or i.get("point") or i.get("item")))
        else:
            out.append(_s(i))
    return [i for i in out if i]


def parse_content(raw):
    """Normalize LLM content (dict OR JSON string) into the canonical schema with safe defaults.
    Missing/malformed fields degrade to empty — never raises. Unknown keys are ignored (forward-compat)."""
    data = raw if isinstance(raw, dict) else _extract_json(raw)
    data = data if isinstance(data, dict) else {}
    header = data.get("header") if isinstance(data.get("header"), dict) else {}
    return {
        "header": {
            "topic": _s(header.get("topic") or data.get("topic")),
            "meeting_date": _s(header.get("meeting_date") or data.get("meeting_date")),
            "meeting_time": _s(header.get("meeting_time") or data.get("meeting_time")),
            "venue": _s(header.get("venue") or data.get("venue")),
        },
        "agenda": _bullets(data.get("agenda")),
        "attendees": [{"name": _s(a.get("name")), "role": _s(a.get("role"))}
                      for a in _list(data.get("attendees")) if isinstance(a, dict)],
        "summary": _s(data.get("summary")),
        "key_points": _bullets(data.get("key_points")),
        "key_figures": _bullets(data.get("key_figures")),
        "speaker_notes": [{"speaker": _s(sn.get("speaker")), "points": _bullets(sn.get("points"))}
                          for sn in _list(data.get("speaker_notes")) if isinstance(sn, dict)],
        "decisions": _bullets(data.get("decisions")),
        "action_items": [{"task": _s(ai.get("task")), "assigned_to": _s(ai.get("assigned_to")),
                          "assigned_by": _s(ai.get("assigned_by")), "due": _s(ai.get("due"))}
                         for ai in _list(data.get("action_items")) if isinstance(ai, dict)],
        "purpose": _s(data.get("purpose")),
    }


# ─────────────────────────────────────────────────────────────────────────────
# Renderer — single source of truth for layout
# ─────────────────────────────────────────────────────────────────────────────
def render_mom(content, lang="English", metadata=None):
    """Render structured `content` into the final MoM text for `lang`. Deterministic: same content +
    metadata always produces byte-identical layout, and every language shares the exact structure.

    metadata: deterministic backend fallback {date, time, venue} (ISO-8601 + 24h). Used only when the
    LLM did not extract that value into content.header (D2)."""
    L = labels_for(lang)
    c = parse_content(content)
    meta = metadata or {}
    ns = L["not_specified"]
    none_stated = L["none_stated"]
    h = c["header"]

    # D2: LLM-extracted header value wins; deterministic backend metadata is the fallback.
    topic = h["topic"]
    date_val = h["meeting_date"] or _s(meta.get("date")) or none_stated
    time_val = h["meeting_time"] or _s(meta.get("time")) or none_stated
    venue_val = h["venue"] or _s(meta.get("venue")) or none_stated

    header = [
        _RULE, "",
        f"{L['title']} | {topic}".rstrip(" |"),
        f"{L['date']}: {date_val}",
        f"{L['time']}: {time_val}",
        f"{L['venue']}: {venue_val}",
        _RULE,
    ]

    def section(heading, body):
        return [heading, *body]

    blocks = [header]

    # AGENDA
    blocks.append(section(L["agenda"], [f"  • {i}" for i in c["agenda"]] or [f"  • {none_stated}"]))

    # ATTENDEES
    att = []
    for a in c["attendees"]:
        name = localize_speaker(a["name"], L)
        att.append(f"  • {name} — {a['role']}" if a["role"] else f"  • {name}")
    blocks.append(section(L["attendees"], att or [f"  • {none_stated}"]))

    # SUMMARY (paragraph)
    blocks.append(section(L["summary"], [f"  {c['summary']}" if c["summary"] else f"  {none_stated}"]))

    # KEY DISCUSSION POINTS — the substantive content of the meeting, one entry per topic.
    # Rendered right after the narrative summary because it is the summary's checklist: the
    # summary is prose and compresses under length pressure, this list does not.
    if c.get("key_points"):
        blocks.append(section(L["key_points"], [f"  • {k}" for k in c["key_points"]]))

    # KEY FIGURES — deliberately OMITTED ENTIRELY when empty, unlike every other section, which
    # falls back to "None explicitly stated." Most meetings (standups, planning, reviews) contain
    # no itemised figures, and an empty "KEY FIGURES: None" heading on those would be noise.
    # Rendering it only when populated makes the section self-conditional: it appears exactly when
    # it has something to say. The section exists because abstractive summarisation reliably drops
    # enumerated figures — the model compresses "eight budget line items" into "a breakdown was
    # presented" to satisfy the summary's length constraint. Giving figures their own home stops
    # them competing with narrative for space.
    if c.get("key_figures"):
        blocks.append(section(L["key_figures"], [f"  • {f}" for f in c["key_figures"]]))

    # SPEAKER-WISE NOTES (skip speakers with no attributed points)
    sn_lines = []
    for sn in c["speaker_notes"]:
        if not sn["points"]:
            continue
        sn_lines.append(f"  {localize_speaker(sn['speaker'], L)}:")
        sn_lines.extend(f"    • {p}" for p in sn["points"])
    blocks.append(section(L["speaker_notes"], sn_lines or [f"  {none_stated}"]))

    # DECISIONS TAKEN
    blocks.append(section(L["decisions"], [f"  • {d}" for d in c["decisions"]] or [f"  • {none_stated}"]))

    # ACTION ITEMS (omit an empty assignee line; due always shows, not_specified if blank)
    ai_lines = []
    for ai in c["action_items"]:
        ai_lines.append(f"  • {ai['task']}")
        if ai["assigned_to"]:
            ai_lines.append(f"    {L['assigned_to']}: {localize_speaker(ai['assigned_to'], L)}")
        if ai["assigned_by"]:
            ai_lines.append(f"    {L['assigned_by']}: {localize_speaker(ai['assigned_by'], L)}")
        ai_lines.append(f"    {L['due_on']}: {ai['due'] or ns}")
    blocks.append(section(L["action_items"], ai_lines or [f"  • {none_stated}"]))

    # PURPOSE OF MEETING (paragraph)
    blocks.append(section(L["purpose"], [f"  {c['purpose']}" if c["purpose"] else f"  {none_stated}"]))

    # Assemble: header ══, AGENDA directly, remaining sections each preceded by ──, then footer.
    parts = ["\n".join(header), "\n".join(blocks[1])]
    for blk in blocks[2:]:
        parts.append(_SUB)
        parts.append("\n".join(blk))
    parts.append(_RULE)
    parts.append(f"{L['regards']}\n{L['generated_by'].format(brand=BRAND)}")

    return "\n\n".join(parts) + "\n"
